-- Pode ser executado novamente sem apagar os dados atuais do campeonato.

create table if not exists public.apep_dados (
  id text primary key,
  pescadores jsonb not null default '[]'::jsonb,
  etapas jsonb not null default '{}'::jsonb,
  etapas_info jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.apep_dados
  add column if not exists pescadores jsonb not null default '[]'::jsonb,
  add column if not exists etapas jsonb not null default '{}'::jsonb,
  add column if not exists etapas_info jsonb not null default '{}'::jsonb,
  add column if not exists updated_at timestamptz not null default now();

-- Cadastre aqui os usuários criados em Authentication > Users no Supabase.
-- O vínculo é feito pelo UUID do usuário; não há senha compartilhada no app.
create table if not exists public.apep_diretores (
  user_id uuid primary key references auth.users(id) on delete cascade,
  nome text not null,
  ativo boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.apep_auditoria (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  responsavel text not null,
  acao text not null,
  detalhes text,
  created_at timestamptz not null default now()
);

alter table public.apep_auditoria
  add column if not exists user_id uuid references auth.users(id) on delete set null;

alter table public.apep_dados enable row level security;
alter table public.apep_diretores enable row level security;
alter table public.apep_auditoria enable row level security;

-- Consulta de autorização executada pelo banco. A lista de diretores não pode
-- ser alterada pelo aplicativo e a função não expõe os demais usuários.
create or replace function public.apep_diretoria_ativa()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.apep_diretores d
    where d.user_id = auth.uid() and d.ativo = true
  );
$$;

revoke all on function public.apep_diretoria_ativa() from public;
grant execute on function public.apep_diretoria_ativa() to authenticated;

-- Remove as políticas antigas, inclusive as que liberavam escrita pública.
do $$
declare policy_row record;
begin
  for policy_row in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename in ('apep_dados', 'apep_diretores', 'apep_auditoria')
  loop
    execute format('drop policy %I on %I.%I', policy_row.policyname, policy_row.schemaname, policy_row.tablename);
  end loop;
end;
$$;

create policy apep_dados_leitura_publica
  on public.apep_dados for select to anon, authenticated
  using (true);

create policy apep_dados_escrita_diretoria
  on public.apep_dados for all to authenticated
  using (public.apep_diretoria_ativa())
  with check (public.apep_diretoria_ativa());

create policy apep_diretores_consulta_propria
  on public.apep_diretores for select to authenticated
  using (user_id = auth.uid());

create policy apep_auditoria_leitura_diretoria
  on public.apep_auditoria for select to authenticated
  using (public.apep_diretoria_ativa());

create policy apep_auditoria_registro_diretoria
  on public.apep_auditoria for insert to authenticated
  with check (public.apep_diretoria_ativa() and user_id = auth.uid());

grant select on public.apep_dados to anon, authenticated;
grant insert, update, delete on public.apep_dados to authenticated;
grant select on public.apep_diretores to authenticated;
grant select, insert on public.apep_auditoria to authenticated;

do $$
declare audit_sequence text;
begin
  audit_sequence := pg_get_serial_sequence('public.apep_auditoria', 'id');
  if audit_sequence is not null then
    execute format('grant usage, select on sequence %s to authenticated', audit_sequence);
  end if;
end;
$$;

